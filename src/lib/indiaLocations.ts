export const INDIA_STATE_OPTIONS = INDIA_STATES_AND_CITIES.map((entry) => entry.state);

export function getCitiesForState(state: string): string[] {
  const normalizedState = state.trim().toLowerCase();
  return INDIA_STATES_AND_CITIES.find((entry) => entry.state.toLowerCase() === normalizedState)?.cities ?? [];
}

export function buildSelectOptions(options: string[], currentValue?: string): string[] {
  const normalizedCurrentValue = currentValue?.trim();
  if (!normalizedCurrentValue) {
    return options;
  }

  const hasCurrentValue = options.some((option) => option.toLowerCase() === normalizedCurrentValue.toLowerCase());
  return hasCurrentValue ? options : [normalizedCurrentValue, ...options];
}
